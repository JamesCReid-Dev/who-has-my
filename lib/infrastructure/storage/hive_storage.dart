/// Hive storage initialization for WhoHasMy.
/// 
/// Initializes five Hive boxes: items, contacts, loans, photos, settings.
/// Entity adapters are registered during initialization.

import 'package:hive_flutter/hive_flutter.dart';

class HiveStorage {
  static const String boxItems = 'items';
  static const String boxContacts = 'contacts';
  static const String boxLoans = 'loans';
  static const String boxPhotos = 'photos';
  static const String boxSettings = 'settings';

  /// Initialize all Hive boxes and register entity adapters.
  /// 
  /// Should be called once at app startup before any UI renders.
  /// Entity adapters (ItemAdapter, ContactAdapter, LoanAdapter) are generated by build_runner.
  static Future<void> initialize() async {
    // Register adapters (generated by build_runner)
    // Hive.registerAdapter(ItemAdapter());
    // Hive.registerAdapter(ContactAdapter());
    // Hive.registerAdapter(LoanAdapter());
    
    // Open boxes
    await Hive.openBox(boxItems);
    await Hive.openBox(boxContacts);
    await Hive.openBox(boxLoans);
    await Hive.openBox(boxPhotos);
    await Hive.openBox(boxSettings);
  }

  /// Close all Hive boxes.
  static Future<void> close() async {
    await Hive.close();
  }
}

